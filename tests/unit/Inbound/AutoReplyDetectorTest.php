    /**
     * @param array<string, array<int, string>> $headers
     */
    #[DataProvider('machineMessages')]
    public function test_machine_generated_message_is_flagged(array $headers, string $from, string $subject, string $expected): void
    {
        self::assertSame($expected, AutoReplyDetector::reason($headers, $from, $subject));
    }

    public function test_rules_also_fire_on_top_of_otherwise_human_headers(): void
    {
        $headers = self::humanHeaders();
        $headers['auto-submitted'] = ['auto-replied'];

        self::assertSame('auto_submitted', AutoReplyDetector::reason($headers, 'john@example.com', 'Re: Olá'));
    }
}
