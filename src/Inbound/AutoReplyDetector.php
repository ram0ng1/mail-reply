<?php

namespace Ramon\MailReply\Inbound;

/**
 * Reconhece mensagens geradas por máquina — respostas automáticas de
 * férias, bounces (DSN), mailer-daemons e spam marcado pelo MTA — que
 * jamais devem virar post. Regras portadas do Discourse
 * (`Email::Receiver#is_auto_generated?`), do GitLab e da RFC 3834.
 * Devolve o motivo ou `null` quando a mensagem parece humana.
 */
class AutoReplyDetector
{
    private const SENDER_PATTERN = '/^(mailer[-_]?daemon|post[-_]?master|no[-_]?reply|do[-_]?not[-_]?reply)@/i';

    private const SUBJECT_PATTERN = '/^\s*(auto(matic)?[\s_-]*(reply|response|antwort)|auto:|out of (the )?office|abwesenheitsnotiz|r[ée]ponse automatique|respuesta autom[áa]tica|resposta autom[áa]tica|delivery status notification|undeliverable|mail delivery (failed|subsystem)|returned mail)/iu';

    private const AUTO_HEADER_PATTERN = '/auto[-_]?(response|submitted|replied|reply|generated|respond)|holidayreply|machinegenerated/i';

    /**
     * @param array<string, array<int, string>|string> $headers nomes em minúsculas
     */
    public static function reason(array $headers, string $from = '', string $subject = ''): ?string
    {
        $get = static fn (string $name): array => array_map('strval', (array) ($headers[$name] ?? []));
        $firstLower = static fn (string $name): string => strtolower(trim((string) ($get($name)[0] ?? '')));

        $autoSubmitted = $firstLower('auto-submitted');
        if ($autoSubmitted !== '' && $autoSubmitted !== 'no') {
            return 'auto_submitted';
        }

        foreach (['x-autoreply', 'x-autorespond', 'x-autogenerated'] as $name) {
            if ($get($name) !== []) {
                return 'auto_reply_header';
            }
        }

        if (preg_match('/\b(bulk|junk|list|auto_reply)\b/', $firstLower('precedence'))) {
            return 'precedence';
        }

        if (str_starts_with($firstLower('content-type'), 'multipart/report')) {
            return 'delivery_report';
        }

        if (array_key_exists('return-path', $headers) && preg_match('/^<?\s*>?$/', $firstLower('return-path'))) {
            return 'null_return_path';
        }

        if ($from !== '' && preg_match(self::SENDER_PATTERN, trim($from))) {
            return 'system_sender';
        }

        if ($subject !== '' && preg_match(self::SUBJECT_PATTERN, $subject)) {
            return 'auto_reply_subject';
        }

        if ($firstLower('x-spam-flag') === 'yes' || str_starts_with($firstLower('x-spam-status'), 'yes')) {
            return 'spam';
        }

        foreach (array_keys($headers) as $name) {
            if (! in_array($name, ['x-auto-response-suppress', 'auto-submitted'], true) && preg_match(self::AUTO_HEADER_PATTERN, (string) $name)) {
                return 'auto_reply_header';
            }
        }

        return null;
    }
}
