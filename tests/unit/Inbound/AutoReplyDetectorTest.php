declare(strict_types=1);

namespace Ramon\MailReply\Tests\unit\Inbound;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Ramon\MailReply\Inbound\AutoReplyDetector;

final class AutoReplyDetectorTest extends TestCase
{
    /**
     * Headers típicos de uma resposta humana do Gmail a uma notificação.
     *
     * @return array<string, array<int, string>>
     */
    private static function humanHeaders(): array
    {
        return [
            'return-path'  => ['<john@example.com>'],
            'from'         => ['John Doe <john@example.com>'],
            'to'           => ['reply+u1d2-aaaaaaaaaaaaaaaa@reply.forum.test'],
            'subject'      => ['Re: Olá mundo #42'],
            'content-type' => ['multipart/alternative; boundary="000000000000abcdef"'],
            'x-gm-message-state' => ['AOJu0Yw'],
            'received'     => ['from mail-sor-f41.google.com by mx.forum.test'],
        ];
    }

    public function test_normal_human_reply_is_not_flagged(): void
    {
        self::assertNull(AutoReplyDetector::reason(self::humanHeaders(), 'john@example.com', 'Re: Olá mundo #42'));
    }

    public function test_auto_submitted_no_is_not_flagged(): void
    {
        $headers = self::humanHeaders() + ['auto-submitted' => ['No']];

        self::assertNull(AutoReplyDetector::reason($headers, 'john@example.com', 'Re: Olá mundo'));
    }

    public function test_x_auto_response_suppress_on_a_human_reply_is_not_flagged(): void
    {
        $headers = self::humanHeaders() + ['x-auto-response-suppress' => ['All']];

        self::assertNull(AutoReplyDetector::reason($headers, 'john@example.com', 'Re: Olá mundo'));
    }

    public function test_subject_that_merely_mentions_automatic_reply_is_not_flagged(): void
    {
        self::assertNull(AutoReplyDetector::reason(self::humanHeaders(), 'john@example.com', 'Re: my automatic reply settings are broken'));
    }

